/**
 * Loads env/{name}.js and produces the env.js source for a build or switch.
 *
 * The local env also embeds the live config as WA_ENV.alternates.live. That is
 * what shows the Local/Live API toggle in the sidebar header. Live (store)
 * builds carry only their own config, so they never show the toggle.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");

/** Envs a local build can switch to from the sidebar toggle. */
const LOCAL_ALTERNATES = ["live"];

function evalEnvFile(envName) {
  const src = path.join(ROOT, "env", `${envName}.js`);
  if (!fs.existsSync(src)) {
    throw new Error(`Missing env file: env/${envName}.js`);
  }
  // Evaluate in a sandbox-ish scope
  const code = fs.readFileSync(src, "utf8");
  // eslint-disable-next-line no-new-func
  const fn = new Function("self", "window", `${code}\n; return typeof WA_ENV !== "undefined" ? WA_ENV : self.WA_ENV;`);
  const env = fn({}, undefined);
  if (!env?.name || !env?.posOrigin) {
    throw new Error(`Invalid WA_ENV in env/${envName}.js`);
  }
  return { env, code };
}

/** @returns {{ env: object, sourceCode: string }} env includes `alternates` for local */
function loadEnvConfig(envName) {
  const { env, code } = evalEnvFile(envName);
  if (envName !== "local") return { env, sourceCode: code };

  const alternates = {};
  for (const name of LOCAL_ALTERNATES) {
    alternates[name] = evalEnvFile(name).env;
  }
  env.alternates = alternates;
  const sourceCode = `${code}
// Generated by scripts/env-source.js — envs the sidebar API toggle can switch to.
WA_ENV.alternates = ${JSON.stringify(alternates, null, 2)};
`;
  return { env, sourceCode };
}

module.exports = { loadEnvConfig };
